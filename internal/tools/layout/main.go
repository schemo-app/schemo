// Command layout writes what the window draws with — the range a panel is dragged between, the two
// strings that hide a value, the settings an installation starts from and the phrase of every HTTP
// status — into the frontend, from the one place they are declared: `domain` and the standard
// library.
//
// It is the same trade as `internal/tools/manifest`: a fact this side owns is written into a file
// on the other side, and a test fails when that file is not what this side would write. Without it
// the window keeps a second copy of every one of them, and the copies drift — the inspector was
// clamped at 260 and 560 in the window while Go clamped the same setting at 220 and 720, so a width
// Go accepts could not be dragged to and a width the window wrote was under Go's own limit.
//
// The generated file is TypeScript rather than JSON because it has to say it is generated, and JSON
// has nowhere to say it.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"log"
	"net/http"
	"os"
	"path/filepath"

	"schemo/internal/domain"
)

// output is where the file goes, named from the repository root — `go run` is called there, and the
// test walks up to the same place.
const output = "frontend/src/lib/layout.ts"

func main() {
	path := filepath.FromSlash(output)
	if err := os.WriteFile(path, rendered(), 0o644); err != nil {
		log.Fatalf("layout: %v", err)
	}
	fmt.Println(path)
}

// rendered is the file as this side would write it. One export per area the window draws with
// numbers, named as the window reads them.
func rendered() []byte {
	var b bytes.Buffer
	b.WriteString("// Generated by `go run ./internal/tools/layout`. Do not edit the numbers:\n")
	b.WriteString("// they are declared in internal/domain, and a test holds this file to them.\n")
	b.WriteString("import type { Settings } from '../../bindings/schemo/internal/domain'\n\n")

	fmt.Fprintf(&b, "export const PANEL = { default: %d, min: %d, max: %d } as const\n",
		domain.DefaultInspectorWidth, domain.MinPanelWidth, domain.MaxPanelWidth)
	fmt.Fprintf(&b, "export const SIDEBAR = { default: %d, min: %d, max: %d } as const\n",
		domain.DefaultSideWidth, domain.MinSideWidth, domain.MaxSideWidth)
	fmt.Fprintf(&b, "export const REQUEST = { min: %d, max: %d } as const\n",
		domain.MinRequestHeight, domain.MaxRequestHeight)
	look := domain.DefaultAppearance()
	fmt.Fprintf(&b, "export const MONO = { default: %d, min: %d, max: %d } as const\n",
		look.MonoSize, domain.MinMonoSize, domain.MaxMonoSize)
	fmt.Fprintf(&b, "export const MCP = { port: %d, tokenPrefix: %q } as const\n",
		domain.DefaultMCPPort, domain.MCPTokenPrefix)
	fmt.Fprintf(&b, "export const PASSWORD = { min: %d, max: %d } as const\n",
		domain.PasswordLeast, domain.PasswordMost)
	fmt.Fprintf(&b, "export const SECRET_MASK = %q\n", domain.SecretMask)
	fmt.Fprintf(&b, "export const INDENT_UNIT = { %s: %q, %s: %q, %s: %q } as const\n",
		domain.IndentTwo, domain.IndentTwo.Unit(), domain.IndentFour, domain.IndentFour.Unit(),
		domain.IndentTab, domain.IndentTab.Unit())

	// What the window shows until it has read the settings: the ones Go starts a fresh installation
	// with, so a switch drawn before the answer arrives is drawn the way it will be.
	// An enum is the string Go writes it as, which the binding's enum type does not take as a
	// literal: hence the cast.
	defaults, err := json.MarshalIndent(domain.DefaultSettings(), "", "  ")
	if err != nil {
		// A settings value that cannot be written as JSON is a program that cannot answer the window.
		panic(err)
	}
	fmt.Fprintf(&b, "export const DEFAULTS = %s as unknown as Settings\n", defaults)

	// The protocol's own phrase for a status, which a chip shows beside the number: the standard
	// library's table is complete and the window has no business keeping a shorter one.
	b.WriteString("export const STATUS_TEXT: Record<number, string> = {\n")
	for code := 100; code < 600; code++ {
		if text := http.StatusText(code); text != "" {
			fmt.Fprintf(&b, "  %d: %q,\n", code, text)
		}
	}
	b.WriteString("}\n")
	return b.Bytes()
}
